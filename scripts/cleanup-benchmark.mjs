import "dotenv/config";
import { PrismaClient } from "@prisma/client";
import { PrismaMariaDb } from "@prisma/adapter-mariadb";
const url=new URL(process.env.DATABASE_URL);
const a=new PrismaMariaDb({host:url.hostname,port:parseInt(url.port||"3306"),user:url.username,password:url.password,database:url.pathname.replace("/",""),ssl:{rejectUnauthorized:false}});
const p=new PrismaClient({adapter:a});
const tenantId=11;
console.log("Deleting benchmark data tenant",tenantId);
const pagDel=await p.pago.deleteMany({where:{tenantId}});
console.log("pagos deleted",pagDel.count);
const presDel=await p.prestamo.deleteMany({where:{tenantId}});
console.log("prestamos deleted",presDel.count);
const userDel=await p.usuario.deleteMany({where:{tenantId}});
console.log("usuarios deleted",userDel.count);
const confDel=await p.configuracionTenant.deleteMany({where:{tenantId}});
console.log("config deleted",confDel.count);
const tenDel=await p.tenant.deleteMany({where:{id:tenantId}});
console.log("tenant deleted",tenDel.count);
await p.$disconnect();
